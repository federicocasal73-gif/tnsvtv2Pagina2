<?php

/**
 * bin/compute-csp-hashes.php
 *
 * Audit AUDIT-2026-09-28 #5: extrae TODOS los event handlers inline
 * (`onclick=`, `oninput=`, etc.) de templates/, calcula el sha256
 * base64 de cada uno y emite el snippet YAML para agregar a
 * `config/packages/nelmio_security.yaml` en script-src.
 *
 * Uso:
 *   php bin/compute-csp-hashes.php > /tmp/csp-hashes.yaml
 *
 * Luego copiar el output a nelmio_security.yaml -> script-src.
 *
 * Re-correr despues de cualquier cambio a un handler.
 */

$templatesDir = __DIR__ . '/../templates';

$handlers = [];

$rii = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($templatesDir));
foreach ($rii as $file) {
    if (!$file->isFile() || $file->getExtension() !== 'twig') {
        continue;
    }
    $content = file_get_contents($file->getPathname());

    // Match on*="..." handlers (single-line only — los handlers multi-line son raros en este repo).
    preg_match_all('/\bon[a-z]+=("([^"]*)"|\'([^\']*)\')/i', $content, $matches);

    foreach ($matches[0] as $i => $full) {
        $value = $matches[2][$i] !== '' ? $matches[2][$i] : $matches[3][$i];
        // CSP hashes solo se aplican a handlers de 1 linea sin 'javascript:' prefix.
        $value = trim($value);
        if ($value === '' || str_starts_with($value, 'javascript:')) {
            continue;
        }
        $handlers[$value][] = str_replace($templatesDir . '/', '', $file->getPathname());
    }
}

ksort($handlers);

$yaml = "# Auto-generated by bin/compute-csp-hashes.php — DO NOT EDIT BY HAND.\n";
$yaml .= "# Re-run after any change to an inline on*=\"...\" handler in templates/.\n";
$yaml .= "# Cada hash cubre el contenido EXACTO del atributo (incluyendo whitespace).\n";
$yaml .= "# CSP3 (RFC 7762): script-src 'sha256-<base64>' permite inline event handlers.\n\n";

$count = 0;
foreach ($handlers as $value => $files) {
    $hash = base64_encode(hash('sha256', $value, true));
    $filesUnique = array_unique($files);
    $fileList = implode(', ', array_slice($filesUnique, 0, 3));
    if (count($filesUnique) > 3) {
        $fileList .= ' (+' . (count($filesUnique) - 3) . ' more)';
    }
    $yaml .= "                - \"'sha256-" . $hash . "'\"\n";
    $yaml .= "                  # "   . sprintf('%-60s # %s', substr($value, 0, 60), $fileList) . "\n";
    $count++;
}

$yaml .= "\n# Total unique handlers: " . $count . "\n";

echo $yaml;